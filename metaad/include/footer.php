             if (current < target) {
                 element.innerHTML = Math.floor(current) + (suffix ? '<span class="stat-suffix">' + suffix + '</span>' :
                     '');
                 requestAnimationFrame(updateCounter);
             } else {
                 element.innerHTML = target + (suffix ? '<span class="stat-suffix">' + suffix + '</span>' : '');
